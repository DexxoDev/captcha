function getValue(source, key) {
  return key.split('.').reduce((value, part) => value?.[part], source);
}

export function normalizeLocale(locale) {
  return locale && translations[locale] ? locale : settings.defaults.guildConfig.language;
}

export function t(locale, key, params = {}) {
  const activeLocale = normalizeLocale(locale);
  const fallback = getValue(translations.en, key);
  const raw = getValue(translations[activeLocale], key) ?? fallback ?? key;

  if (typeof raw !== 'string') {
    return raw;
  }

  return raw.replace(/\{\{(\w+)\}\}/g, (_, token) => `${params[token] ?? ''}`);
}

export function localeLabel(locale, viewerLocale = locale) {
  return t(viewerLocale, `common.languages.${normalizeLocale(locale)}`);
}

export function verificationRoleNames(locale) {
  const activeLocale = normalizeLocale(locale);

  return {
    unverified: {
      name: t(activeLocale, 'roles.unverified'),
      aliases: ['Unverified', 'غير موثق'],
    },
    verified: {
      name: t(activeLocale, 'roles.verified'),
      aliases: ['Verified', 'موثق'],
    },
  };
}
